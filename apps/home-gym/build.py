#!/usr/bin/env python3
"""Independent, deterministic Home Gym artifact. No network or hosting side effects."""
from pathlib import Path
import argparse
import hashlib
import io
import json
import tarfile

ROOT = Path(__file__).resolve().parent
SOURCE = ('index.html', 'styles.css', 'app.mjs', 'engine.mjs', 'program.mjs',
          'manifest.webmanifest', 'icon.svg', 'source-inventory.json', 'coaching.mjs', 'experience.mjs', 'rest.mjs', 'condition.mjs', 'condition-ui.mjs')

def sha(data):
    return hashlib.sha256(data).hexdigest()

def encoded(value):
    return (json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(',', ':')) + '\n').encode()

def build():
    files = {name: (ROOT / name).read_bytes() for name in SOURCE}
    program = json.loads(files['program.mjs'].decode().split('export const PROGRAM = ')[1].rsplit(';', 1)[0])
    version = dict(programId=program['programId'], programVersion=program['programVersion'],
                   sourceSHA256=program['sourceSHA256'], contentSHA256=sha(encoded({n: sha(v) for n, v in files.items()})))
    files['version.json'] = encoded(version)
    types = {'.html': ['text/html'], '.css': ['text/css'], '.mjs': ['application/javascript', 'text/javascript'],
             '.json': ['application/json'], '.webmanifest': ['application/manifest+json', 'application/json'], '.svg': ['image/svg+xml']}
    runtime = (ROOT / 'sw-runtime.js').read_bytes()
    identity = dict(release=program['programVersion'], runtime_sha256=sha(runtime), assets=[
        dict(name=n, size=len(v), sha256=sha(v), types=types[Path(n).suffix]) for n, v in sorted(files.items())])
    identity['id'] = sha(encoded(identity))
    files['sw.js'] = b'// Generated by apps/home-gym/build.py; do not edit.\nconst BUILD = ' + encoded(identity).rstrip() + b';\n' + runtime
    manifest = dict(schema=1, programId=program['programId'], programVersion=program['programVersion'],
                    sourceSHA256=program['sourceSHA256'], buildId=identity['id'],
                    publication='manual-only; separate origin; owner authorization required',
                    files={n: dict(size=len(v), sha256=sha(v)) for n, v in sorted(files.items())})
    files['artifact.json'] = encoded(manifest)
    return files

def archive(files):
    out = io.BytesIO()
    with tarfile.open(fileobj=out, mode='w', format=tarfile.USTAR_FORMAT) as handle:
        for name, data in sorted(files.items()):
            entry = tarfile.TarInfo(name)
            entry.size = len(data)
            entry.mode = 0o644
            entry.mtime = entry.uid = entry.gid = 0
            entry.uname = entry.gname = ''
            handle.addfile(entry, io.BytesIO(data))
    return out.getvalue()

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--out', type=Path)
    args = parser.parse_args()
    files = build()
    for name in ('version.json', 'sw.js', 'artifact.json'):
        if args.check:
            assert (ROOT / name).read_bytes() == files[name], 'Stale generated file: ' + name
        else:
            (ROOT / name).write_bytes(files[name])
    if args.out:
        target = args.out.resolve()
        assert target != ROOT and not target.is_relative_to(ROOT), 'Use a separate output directory'
        target.mkdir(parents=True, exist_ok=True)
        assert not any(target.iterdir()), 'Output directory must be empty'
        for name, data in files.items():
            (target / name).write_bytes(data)
        (target / 'home-gym.tar').write_bytes(archive(files))
    print('PASS | HOME_GYM_ARTIFACT ' + str(len(files)) + ' allowlisted files; tar SHA-256 ' + sha(archive(files)))
