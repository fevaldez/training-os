#!/usr/bin/env python3
"""Deterministic public shell metadata; --check never changes files or publishes."""
from pathlib import Path
import hashlib,json,sys
ROOT=Path(__file__).resolve().parents[1]
ASSETS=('index.html','version.json','manifest.webmanifest','training-os-loop-v1-180.png','training-os-loop-v1-192.png','training-os-loop-v1-512.png','training-os-loop-v1-1024.png')
PUBLIC=(*ASSETS,'sw.js')
def sha(data): return hashlib.sha256(data).hexdigest()
def build(root=ROOT):
    runtime=(root/'scripts/sw-runtime.js').read_text()
    assets=[]
    for name in ASSETS:
        data=(root/name).read_bytes()
        types=['text/html'] if name.endswith('.html') else ['application/json'] if name.endswith('.json') else ['application/manifest+json','application/json'] if name.endswith('.webmanifest') else ['image/png']
        assets.append(dict(name=name,size=len(data),sha256=sha(data),types=types))
    identity=dict(release=json.loads((root/'version.json').read_text())['release'],assets=assets,runtime_sha256=sha(runtime.encode()))
    identity['id']=sha(json.dumps(identity,sort_keys=True,separators=(',',':')).encode())
    return '// Generated by scripts/build_offline.py; do not edit.\nconst BUILD = '+json.dumps(identity,sort_keys=True,separators=(',',':'))+';\n'+runtime
if __name__=='__main__':
    output=build(); target=ROOT/'sw.js'
    if '--check' in sys.argv:
        if target.read_text()!=output: raise SystemExit('FAIL: stale offline metadata; run python3 scripts/build_offline.py')
        print('PASS | offline metadata: 7 size/type/SHA-256 pins; deterministic worker')
    else:
        target.write_text(output)
        print('Built sw.js from 7 public shell assets and pinned runtime')
